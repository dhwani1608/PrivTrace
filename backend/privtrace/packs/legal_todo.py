"""Generate docs/LEGAL_REVIEW_TODO.md from the packs, so it can never drift."""

from __future__ import annotations

from privtrace.packs.schema import Pack

HEADER = """# Legal review TODO

> Generated by `privtrace packs legal-todo` from `packs/*.yaml`. Do not edit by hand —
> fix the pack and regenerate.

Every rule whose `reference_verified` is `false` is listed here. A human must check the
section/rule number **and** the `source_url` against the official text, then set
`reference_verified: true` in the pack. PrivTrace never invents citations; where a number
is uncertain it is flagged here rather than guessed.

Also open:
- **"TAD"** framework mentioned in the brief is unidentified — no pack exists yet.
- Source URLs for Indian packs point to the ministry/agency landing pages; replace with
  deep links to the exact notified text once confirmed.
"""


def render_legal_todo(packs: list[Pack]) -> str:
    out = [HEADER]
    total = 0
    for pack in packs:
        todo = pack.unverified_references
        if not todo:
            continue
        total += len(todo)
        out.append(f"\n## {pack.name} (`{pack.id}`)\n")
        out.append("| Rule | Title | Reference to verify | Source |")
        out.append("|---|---|---|---|")
        for r in todo:
            out.append(f"| `{r.id}` | {r.title} | {r.reference} | <{r.source_url}> |")
    out.append(f"\n**{total} reference(s) awaiting verification.**\n")
    return "\n".join(out)
